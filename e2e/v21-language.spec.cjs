'use strict';
const {test,expect}=require('@playwright/test');

test('v21 story/home/events/photo switch RU/EN with intact player drafts',async({page})=>{
 const errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');
 await page.locator('#languageSelect').selectOption('en');
 await page.locator('#createBtn').click();
 await expect(page.locator('#roomCode')).toHaveText(/^[A-HJ-NP-Z2-9]{6}$/,{timeout:15000});
 await page.evaluate(()=>window.GameV21.open('story'));
 const modal=page.locator('.v21-dialog');
 await expect(modal).toBeVisible();
 await expect(modal.locator('.v21-body')).toContainText('Quiet moments');
 await expect(modal.locator('.v21-body')).toContainText('Our storybook');
 const draft=modal.locator('#v21-letter-draft');
 await draft.fill('Моя личная записка · Aiko ✦');
 await modal.locator('[data-dialog-language]').selectOption('ru');
 await expect(modal.locator('.v21-body')).toContainText('Моменты тишины');
 await expect(draft).toHaveValue('Моя личная записка · Aiko ✦');
 await modal.locator('[data-dialog-language]').selectOption('en');
 await expect(modal.locator('.v21-body')).toContainText('Sealed letters');
 await expect(draft).toHaveValue('Моя личная записка · Aiko ✦');
 await expect(draft).toHaveAttribute('placeholder','A short note for your partner');
 await modal.locator('[data-gallery-tab="home"]').click();
 await expect(modal.locator('.v21-body')).toContainText('Living garden');
 await expect(modal.locator('.v21-body')).toContainText('Music room');
 await expect(modal.locator('.v21-body')).toContainText('Our shared painting');
 await modal.locator('[data-gallery-tab="events"]').click();
 await expect(modal.locator('.v21-body')).toContainText('Weekly challenge');
 await expect(modal.locator('.v21-body')).toContainText('Seasonal chapters');
 await expect(modal.locator('.v21-body')).toContainText('Museum of shared victories');
 await modal.locator('[data-gallery-tab="level"]').click();
 await expect(modal.locator('.v21-body')).toContainText('New co-op challenges');
 await expect(modal.locator('.v21-body')).toContainText('Chapter v21 · 10 challenges');
 await modal.locator('[data-gallery-tab="story"]').click();
 await expect(modal.locator('#v21-letter-draft')).toHaveValue('Моя личная записка · Aiko ✦');
 await modal.locator('[data-gallery-tab="photo"]').click();
 const caption=modal.locator('#v21-photo-caption');
 await expect(caption).toHaveAttribute('placeholder','Our shared journey');
 await caption.fill('Custom draft · Наша игра');
 await modal.locator('[data-dialog-language]').selectOption('ru');
 await expect(modal.locator('.v21-body')).toContainText('Фоторежим');
 await expect(caption).toHaveValue('Custom draft · Наша игра');
 await modal.locator('[data-dialog-language]').selectOption('en');
 await expect(modal.locator('.v21-body')).toContainText('Photo mode');
 await expect(caption).toHaveValue('Custom draft · Наша игра');
 await modal.locator('[data-gallery-tab="story"]').click();
 await expect(modal.locator('#v21-letter-draft')).toHaveValue('Моя личная записка · Aiko ✦');
 expect(errors).toEqual([]);
});
